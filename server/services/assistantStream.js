/** Keep the agent's control packets out of visible conversation, including partial fences. */
export function visibleAssistantText(text = '') {
  const source = String(text);
  const fence = /```(?:json)?\s*\{\s*"(?:tool|name|action|function)"/i.exec(source);
  const bare = /\{\s*"(?:tool|name|action|function)"\s*:/.exec(source);
  const partial =
    (source.match(/```/g) || []).length % 2 === 1
      ? /```(?:j(?:s(?:o(?:n)?)?)?)?\s*$/.exec(source)
      : null;
  const positions = [fence?.index, bare?.index, partial?.index].filter(Number.isFinite);
  if (/^\s*```json\s*$/i.test(source)) return '';
  return positions.length ? source.slice(0, Math.min(...positions)).trimEnd() : source;
}

export function responseWithToolCall(result, fallback = '') {
  const call = result?.toolCalls?.[0];
  const text = result?.text || fallback || '';
  if (!call) return text;
  const args = JSON.parse(call.function?.arguments || '{}');
  return `${text}\n\n\`\`\`json\n${JSON.stringify({ tool: call.function.name, args })}\n\`\`\``;
}

export function extractToolCall(text) {
  if (typeof text !== 'string') return null;
  const start = text.search(/\{\s*"(?:tool|function|name)"\s*:/i);
  if (start < 0) return null;
  let depth = 0,
    quoted = false,
    escaped = false;
  for (let i = start; i < text.length; i++) {
    const ch = text[i];
    if (escaped) {
      escaped = false;
      continue;
    }
    if (quoted && ch === '\\') {
      escaped = true;
      continue;
    }
    if (ch === '"') {
      quoted = !quoted;
      continue;
    }
    if (!quoted) {
      if (ch === '{') depth++;
      if (ch === '}' && --depth === 0) {
        const raw = text.slice(start, i + 1);
        try {
          const call = JSON.parse(raw);
          return call.tool || call.name || call.function?.name ? raw : null;
        } catch {
          return null;
        }
      }
    }
  }
  return null;
}

export function nativeToolChoice(query, available) {
  const text = String(query || '').trim();
  if (
    /\b(?:do not|don['’]t|without)\s+(?:run|use|execute|call)\s+(?:any\s+)?tools?\b|\b(?:explain|answer|plan) only\b/i.test(
      text,
    )
  )
    return 'auto';
  const explicit =
    /^(?:please\s+)?(?:use|invoke|call)\s+(?:the\s+)?(?:registered\s+)?`?([a-z][a-z0-9_]+)`?/i.exec(
      text,
    )?.[1];
  if (explicit && available.has(explicit))
    return { type: 'function', function: { name: explicit } };
  // A concrete navigation request has a known first operation. Selecting it
  // avoids leaving the gateway to interpret an ambiguous `required` choice.
  // Arguments are still generated by the model and execution still uses the
  // normal runtime permission gate. Subsequent actions remain model-directed.
  const opening =
    /^(?:please\s+)?(?:(?:can|could|would|will)\s+you\s+)?(?:open|visit|browse|navigate|go\s+to)\b/i.test(
      text,
    );
  const withoutEmails = text.replace(/[\w.+%-]+@[\w.-]+\.[a-z]{2,}/gi, '');
  const address =
    /https?:\/\/\S+|(?<![@\w])(?:localhost(?::\d+)?|(?:[\w-]+\.)+[a-z]{2,})(?=[:/\s,?!]|$)/i.test(
      withoutEmails,
    );
  if (opening && address && /\bbrowser\b/i.test(text) && available.has('open_workspace_browser'))
    return { type: 'function', function: { name: 'open_workspace_browser' } };
  return /^(?:please\s+)?(?:(?:can|could|would|will)\s+you\s+)?(?:run|execute|open|read|write|save|build|create|implement|browse|search|inspect|analy[sz]e|fix|modify|update|delete|send)\b/i.test(
    text,
  )
    ? 'required'
    : 'auto';
}

/** Browser field values belong to the page, not activity, logs or progress prompts. */
export function publicToolArguments(tool, args = {}) {
  if (tool === 'browser_type') return { ...args, text: '[private input]' };
  if (tool === 'browser_fill_form')
    return {
      ...args,
      fields: Array.isArray(args.fields)
        ? args.fields.map((field) => ({ ...field, value: '[private input]' }))
        : '[private inputs]',
    };
  return args;
}
