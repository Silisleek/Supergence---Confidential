// SIS 1.0 — AREM Neural Gateway Client
// Dedicated agent gateway for the Supergence AREM Team
// Powered by opus-4.6 via http://127.0.0.1:20128/v1

export const AREM_DEFAULT_ENDPOINT = process.env.AREM_BASE_URL || 'http://127.0.0.1:20128/v1';
export const AREM_DEFAULT_KEY = process.env.AREM_API_KEY || '';
export const AREM_DEFAULT_MODEL = process.env.AREM_MODEL || 'opus-4.6';

export class AremClient {
  constructor({
    baseURL = AREM_DEFAULT_ENDPOINT,
    apiKey = AREM_DEFAULT_KEY,
    model = AREM_DEFAULT_MODEL,
    timeoutMs = 60000,
  } = {}) {
    this.baseURL = baseURL.replace(/\/+$/, '');
    this.apiKey = apiKey;
    this.model = model;
    this.timeoutMs = timeoutMs;
  }

  async complete({
    systemPrompt = '',
    prompt = '',
    messages = null,
    model = null,
    maxTokens = 2048,
    temperature = 0.3,
  } = {}) {
    const activeModel = model || this.model;
    const chatMessages = messages
      ? [...messages]
      : [
          ...(systemPrompt ? [{ role: 'system', content: systemPrompt }] : []),
          { role: 'user', content: prompt },
        ];

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), this.timeoutMs);
    const t0 = Date.now();

    try {
      const response = await fetch(`${this.baseURL}/chat/completions`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${this.apiKey}`,
        },
        body: JSON.stringify({
          model: activeModel,
          messages: chatMessages,
          max_tokens: maxTokens,
          temperature,
        }),
        signal: controller.signal,
      });

      if (!response.ok) {
        const errorText = await response.text().catch(() => '');
        throw new Error(
          `AREM gateway HTTP ${response.status} (${response.statusText}): ${errorText.slice(0, 300)}`,
        );
      }

      const data = await response.json();
      const choice = data.choices?.[0];
      const message = choice?.message || {};
      const content = (message.content || '').trim();
      const reasoning = (message.reasoning_content || '').trim();

      return {
        text: content || reasoning || '',
        content,
        reasoning,
        model: data.model || activeModel,
        durationMs: Date.now() - t0,
        usage: data.usage || null,
        raw: data,
      };
    } finally {
      clearTimeout(timer);
    }
  }

  /**
   * Helper to parse JSON output generated by an agent.
   * Strips markdown fences (```json ... ```) and extracts valid JSON.
   */
  extractJson(text) {
    if (!text || typeof text !== 'string') return null;
    let clean = text.trim();

    // 1. Check for fenced code blocks
    const fenceMatch = clean.match(/```(?:json)?\s*([\s\S]*?)\s*```/i);
    if (fenceMatch && fenceMatch[1]) {
      clean = fenceMatch[1].trim();
    }

    // 2. Direct JSON parse
    try {
      return JSON.parse(clean);
    } catch (_) {}

    // 3. Scan for first { or [ to matching end
    const firstBrace = clean.indexOf('{');
    const firstBracket = clean.indexOf('[');
    let startIdx = -1;
    let endChar = '}';

    if (firstBrace !== -1 && (firstBracket === -1 || firstBrace < firstBracket)) {
      startIdx = firstBrace;
      endChar = '}';
    } else if (firstBracket !== -1) {
      startIdx = firstBracket;
      endChar = ']';
    }

    if (startIdx !== -1) {
      const lastIdx = clean.lastIndexOf(endChar);
      if (lastIdx > startIdx) {
        try {
          return JSON.parse(clean.slice(startIdx, lastIdx + 1));
        } catch (_) {}
      }
    }

    return null;
  }
}

export const aremClient = new AremClient();
export default aremClient;
